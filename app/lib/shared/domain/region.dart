/// 팀 활동 지역 (data-model.md v4.7 3-1 `region_sido`·`region_sigungu`, Q-079 4번).
///
/// - 시·도 + 시·군·구, 둘 다 선택. 시·군·구는 시·도 없이 가질 수 없다(서버도 같은 검사).
/// - 값은 아래 [KoreaRegions] 정적 목록의 글자를 그대로 저장한다(예: "서울", "성동구").
///   시·도는 짧은 표기(카카오 주소와 같은 꼴), 일반구가 있는 시는 "성남시 분당구" 처럼 시와 구를 함께 쓴다.
/// - 지정 풋살장을 카카오 검색으로 고르면 주소에서 자동으로 채운다([regionFromAddress]). 직접 입력 구장은 채우지 않는다.
class Region {
  const Region(this.sido, [this.sigungu]);

  final String sido;
  final String? sigungu;

  /// 화면 표시 ("서울 성동구", 시·군·구가 없으면 "서울").
  String get label => sigungu == null ? sido : '$sido $sigungu';

  /// teams 표·검색 결과 줄에서. 시·도가 없으면 null.
  static Region? fromRow(Map<String, dynamic> row) {
    final sido = row['region_sido'] as String?;
    if (sido == null || sido.isEmpty) return null;
    final sigungu = row['region_sigungu'] as String?;
    return Region(sido, (sigungu == null || sigungu.isEmpty) ? null : sigungu);
  }

  @override
  bool operator ==(Object other) => other is Region && other.sido == sido && other.sigungu == sigungu;

  @override
  int get hashCode => Object.hash(sido, sigungu);

  @override
  String toString() => 'Region($label)';
}

