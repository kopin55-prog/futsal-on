/// 카카오 장소 주소("서울 성동구 성수이로 1", "서울특별시 성동구 …", "경기 성남시 분당구 …")에서 활동 지역을 읽는다.
///
/// - 시·도를 모르면 null (자동 채움 없음).
/// - 시·군·구는 목록에 있는 값만. "성남시 분당구" 처럼 두 단어인 값을 먼저 맞춰 본다.
///   일반구가 있는 시인데 주소에 구가 없으면(예: 옛 주소 "경기 화성시 …") 시·군·구는 비운다.
/// - 세종처럼 시·군·구가 없는 시·도는 시·도만.
Region? regionFromAddress(String? address) {
  if (address == null) return null;
  final words = address.trim().split(RegExp(r'\s+')).where((w) => w.isNotEmpty).toList();
  if (words.isEmpty) return null;
  final sido = KoreaRegions.normalizeSido(words.first);
  if (sido == null) return null;
  final options = KoreaRegions.sigunguOf(sido);
  String? sigungu;
  if (words.length >= 3 && options.contains('${words[1]} ${words[2]}')) {
    sigungu = '${words[1]} ${words[2]}';
  } else if (words.length >= 2 && options.contains(words[1])) {
    sigungu = words[1];
  }
  return Region(sido, sigungu);
}

/// 지정 풋살장을 바꿨을 때의 활동 지역 (Q-079 4번).
///
/// - 카카오 검색으로 고른 구장이고 주소에서 시·도를 읽으면 그 값으로 채운다(이후 사용자가 바꾸거나 비울 수 있다).
/// - 직접 입력한 구장, 구장 지우기, 주소에서 지역을 못 읽은 경우는 지금 값을 그대로 둔다.
Region? regionAfterVenueChange(Venue? venue, Region? current) {
  if (venue == null || !venue.isFromMap) return current;
  return regionFromAddress(venue.address) ?? current;
}
